/**
 * What a feed covers. `top` is the country's or region's main headlines
 * (`countries/FR.json`); the others are section feeds (sport, business), each
 * clustered into a file of its own (`countries/FR.sport.json`).
 */
export { CATEGORIES, type Category };

/**
 * Categories the ingest fetches and writes files for. A category left out
 * keeps its feeds in SOURCES (checked with `pnpm probe`) without requesting them.
 */
export const FETCHED_CATEGORIES: readonly Category[] = CATEGORIES;

/** A source's feed URLs in the given categories, in category order. */
export function feedUrlsOf(source: SourceConfig, categories: readonly Category[] = FETCHED_CATEGORIES): string[] {
  return categories.flatMap((c) => source.feeds[c] ?? []);
}

export interface SourceConfig {
  /** Stable id; also the outlet identity used for "distinct outlets". */
  id: string;
  name: string;
  /** Adapter that fetches this source (see adapters/). */
  type: 'rss';
  country: CountryCode;
  language: string;
  /**
   * Feed URLs for this outlet, by category. For `top`, prefer national /
   * politics / society section feeds over "all news" feeds, which mix in
   * international stories. A specialist outlet (a sports daily) has no `top`.
   */
  feeds: Partial<Record<Category, string[]>>;
  /** Relative editorial authority, used to pick a cluster's representative. Higher wins. */
  authority: number;
  /**
   * Regional outlet: its articles go to `regions/{region}.json` (see REGIONS)
   * instead of the national file. Use local-section feeds, since regional
   * papers' main feeds carry national and world news too.
   */
  region?: RegionCode;
}

